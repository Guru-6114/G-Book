/// Lets any widget write `context.l10n.get('key')` instead of the longer
/// `AppLocalizations.of(context).get('key')`. This is what was missing —
/// `sms_settings_screen.dart` and `payment_settings_screen.dart` both call
/// `context.l10n`, but without this extension `BuildContext` has no such
/// getter, hence the `undefined_getter` errors.
extension AppLocalizationsExtension on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
