// lib/l10n/app_localizations.dart
// Simple in-app localization without external packages.
//
// FIX: AppLocalizations.of(context) used to always return AppLocalizations('en')
// no matter what language was selected — that's the root cause of "language
// picker doesn't actually change anything". It now reads the live language
// from LocaleProvider (via Provider.of), so every widget that calls
// AppLocalizations.of(context).get('key') automatically rebuilds and shows
// the new language the instant the user taps a language in LanguageScreen.
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../providers/locale_provider.dart';

class AppLocalizations {
  final String languageCode;
  const AppLocalizations(this.languageCode);

  /// Reads the *current* language from LocaleProvider instead of a
  /// hardcoded 'en'. Listens for changes, so widgets using this rebuild
  /// automatically when the user switches language anywhere in the app.
  static AppLocalizations of(BuildContext context) {
    final code = context.watch<LocaleProvider>().languageCode;
    return AppLocalizations(code);
  }

  String get(String key) {
    final map = _translations[languageCode] ?? _translations['en']!;
    return map[key] ?? _translations['en']![key] ?? key;
  }

